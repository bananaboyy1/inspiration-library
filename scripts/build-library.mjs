// Usage:
//   node scripts/build-library.mjs          regenerate LIBRARY.md from entries/*.json
//   node scripts/build-library.mjs --check  validate entries and fail if LIBRARY.md is out of date
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const DISCIPLINES = [
  ['web', 'Web'],
  ['app', 'App'],
  ['branding', 'Branding'],
  ['print-social', 'Print & Social'],
]
const REQUIRED = ['name', 'image', 'discipline', 'designType', 'title', 'tags', 'whatItIs', 'whatItMeans', 'techniques', 'bestFor', 'vocabulary']
const check = process.argv.includes('--check')

const dir = path.join(root, 'entries')
const entries = fs
  .readdirSync(dir)
  .filter((f) => f.endsWith('.json'))
  .map((f) => ({ file: f, data: JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8').replace(/^﻿/, '')) }))

// ---- validation ----
const problems = []
for (const { file, data: e } of entries) {
  const base = file.replace(/\.json$/, '')
  for (const k of REQUIRED) if (e[k] == null || e[k] === '') problems.push(`${file}: missing "${k}"`)
  if (e.name !== base) problems.push(`${file}: name "${e.name}" does not match filename`)
  if (!DISCIPLINES.some(([s]) => s === e.discipline)) problems.push(`${file}: bad discipline "${e.discipline}"`)
  else if (!base.startsWith(e.discipline + '-')) problems.push(`${file}: filename must start with "${e.discipline}-"`)
  if (e.image && !fs.existsSync(path.join(root, e.image))) problems.push(`${file}: image not found (${e.image})`)
  if (!fs.existsSync(path.join(dir, base + '.md'))) problems.push(`${file}: missing ${base}.md`)
  for (const v of e.vocabulary || []) if (!v.term || !v.definition) problems.push(`${file}: vocabulary item needs term and definition`)
}
for (const f of fs.readdirSync(dir)) {
  if (f.endsWith('.md') && !fs.existsSync(path.join(dir, f.replace(/\.md$/, '.json')))) problems.push(`${f}: no matching .json`)
}

// ---- build ----
const oneLine = (s, n = 220) => {
  const t = String(s).replace(/\s+/g, ' ').trim()
  const first = t.match(/^.*?[.!?](\s|$)/)?.[0].trim() || t
  const out = first.length <= n ? first : t.slice(0, n).replace(/\s+\S*$/, '') + '…'
  return out
}
const byTitle = (a, b) => a.data.title.localeCompare(b.data.title)

let md = `# Design Inspiration Library

An open reference for web, app, branding and print/social design. **Nothing here is a rule.** Browse it, borrow from it, mix disciplines.

> Generated by \`npm run library\` from \`entries/*.json\`. Do not edit by hand — edit the entry JSON/MD and regenerate.

**${entries.length} entries**\n\n`

md += DISCIPLINES.map(([slug, label]) => {
  const n = entries.filter((e) => e.data.discipline === slug).length
  return `- [${label} (${n})](#${label.toLowerCase().replace(/[^a-z0-9 ]/g, '').replace(/ +/g, '-')})`
}).join('\n') + '\n'

for (const [slug, label] of DISCIPLINES) {
  const inDisc = entries.filter((e) => e.data.discipline === slug)
  md += `\n---\n\n## ${label}\n\n${inDisc.length} entries\n\n`
  const types = new Map()
  for (const e of inDisc) {
    if (!types.has(e.data.designType)) types.set(e.data.designType, [])
    types.get(e.data.designType).push(e)
  }
  const sorted = [...types.entries()].sort((a, b) => b[1].length - a[1].length || a[0].localeCompare(b[0]))
  md += sorted.map(([t, list]) => `- ${t} (${list.length})`).join('\n') + '\n'
  for (const [t, list] of sorted) {
    md += `\n### ${label} › ${t} (${list.length})\n\n`
    for (const { data: e } of list.sort(byTitle)) {
      md += `- **[${e.title}](entries/${e.name}.md)** — ${oneLine(e.whatItIs)}\n`
      md += `  - Techniques: ${e.techniques.map((x) => x.replace(/\s+/g, ' ').replace(/[.;]+$/, '')).join('; ')}\n`
      md += `  - Best for: ${e.bestFor.map((x) => x.replace(/\s+/g, ' ').replace(/[.;]+$/, '')).join('; ')}\n`
      md += `  - Image: \`${e.image}\`\n`
    }
  }
}

const target = path.join(root, 'LIBRARY.md')
if (check) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : ''
  if (current !== md) problems.push('LIBRARY.md is out of date — run `npm run library`')
  if (problems.length) {
    console.error(problems.join('\n'))
    process.exit(1)
  }
  console.log(`OK: ${entries.length} entries, LIBRARY.md in sync`)
} else {
  fs.writeFileSync(target, md, 'utf8')
  if (problems.length) console.error(`Wrote LIBRARY.md, but found ${problems.length} problem(s):\n` + problems.join('\n'))
  else console.log(`LIBRARY.md written (${entries.length} entries)`)
}
